//! Challenge-bound freshness and in-process replay protection for policy observations.
//!
//! This module supplements (and does not replace) v1 receipt reconciliation. The
//! caller must persist nonce consumption transactionally before promotion if replay
//! protection must survive process restarts. Hashes provide byte binding, not
//! signatures, trusted time, device identity, or hardware attestation.

use std::collections::HashSet;

use serde_json::{Value, json};

const CHALLENGE_SCHEMA: &str =
    include_str!("../../../schemas/edge-policy-verification-challenge-v1.schema.json");
const ENVELOPE_SCHEMA: &str =
    include_str!("../../../schemas/edge-policy-freshness-envelope-v1.schema.json");
const RECEIPT_SCHEMA: &str =
    include_str!("../../../schemas/edge-policy-observation-receipt-v1.schema.json");
const MAX_CHALLENGE_LIFETIME_MS: u64 = 3_600_000;

/// Tracks challenge nonces consumed by this verifier process.
///
/// This state is in-memory only. A production promotion gate must persist nonce
/// consumption durably and atomically with the promotion decision.
#[derive(Debug, Default)]
pub struct ChallengeReplayGuard {
    consumed_nonces: HashSet<String>,
}

impl ChallengeReplayGuard {
    /// Create an empty replay guard. It has no persistent state.
    #[must_use]
    pub fn new() -> Self {
        Self::default()
    }

    /// Validate conformance, byte binding, challenge bindings, and receipt age,
    /// then consume the nonce only after all checks succeed.
    ///
    /// `verifier_now_unix_ms` must come from the verifier's clock, not the receipt.
    /// `corpus_source` is the exact corpus byte string whose digest was challenged.
    /// `receipt_source` is the exact receipt byte string digest-bound by the envelope.
    ///
    /// This method rejects schema-valid stale or replayed receipts; it does not
    /// authenticate the sender or its clock. The nonce must be generated by the
    /// verifier using a cryptographically secure random source.
    pub fn verify_and_consume(
        &mut self,
        challenge_source: &str,
        envelope_source: &str,
        corpus_schema_source: &str,
        corpus_source: &str,
        receipt_source: &str,
        verifier_now_unix_ms: u64,
    ) -> Result<Value, Vec<String>> {
        let challenge = super::validate_document(CHALLENGE_SCHEMA, challenge_source, "challenge")?;
        let envelope =
            super::validate_document(ENVELOPE_SCHEMA, envelope_source, "freshness envelope")?;
        let receipt = super::validate_document(RECEIPT_SCHEMA, receipt_source, "receipt")?;

        let challenge_id = string_field(&challenge, "/challenge_id", "challenge.challenge_id")?;
        let nonce = string_field(&challenge, "/nonce", "challenge.nonce")?;
        if self.consumed_nonces.contains(nonce) {
            return Err(vec![
                "challenge nonce has already been consumed by this verifier process".to_owned(),
            ]);
        }

        let issued_at = integer_field(
            &challenge,
            "/issued_at_unix_ms",
            "challenge.issued_at_unix_ms",
        )?;
        let expires_at = integer_field(
            &challenge,
            "/expires_at_unix_ms",
            "challenge.expires_at_unix_ms",
        )?;
        let max_receipt_age = integer_field(
            &challenge,
            "/max_receipt_age_ms",
            "challenge.max_receipt_age_ms",
        )?;
        let generation = integer_field(
            &challenge,
            "/policy_generation",
            "challenge.policy_generation",
        )?;

        if expires_at <= issued_at {
            return Err(vec![
                "challenge expiry must be after its issue time".to_owned(),
            ]);
        }
        if expires_at - issued_at > MAX_CHALLENGE_LIFETIME_MS {
            return Err(vec![format!(
                "challenge lifetime exceeds the maximum of {MAX_CHALLENGE_LIFETIME_MS} ms"
            )]);
        }
        if verifier_now_unix_ms < issued_at || verifier_now_unix_ms > expires_at {
            return Err(vec![
                "challenge is not current at the verifier's supplied time".to_owned(),
            ]);
        }

        let envelope_challenge_id =
            string_field(&envelope, "/challenge_id", "envelope.challenge_id")?;
        let envelope_nonce = string_field(&envelope, "/nonce", "envelope.nonce")?;
        if envelope_challenge_id != challenge_id || envelope_nonce != nonce {
            return Err(vec![
                "freshness envelope does not bind the current challenge ID and nonce".to_owned(),
            ]);
        }

        let envelope_run_id = string_field(&envelope, "/run_id", "envelope.run_id")?;
        let receipt_run_id = string_field(&receipt, "/run_id", "receipt.run_id")?;
        if envelope_run_id != receipt_run_id {
            return Err(vec![
                "freshness envelope run_id does not match the receipt".to_owned(),
            ]);
        }
        let envelope_generation = integer_field(
            &envelope,
            "/policy_generation",
            "envelope.policy_generation",
        )?;
        if envelope_generation != generation {
            return Err(vec![
                "freshness envelope policy_generation does not match the challenge".to_owned(),
            ]);
        }

        let actual_receipt_sha256 = super::sha256_hex(receipt_source.as_bytes());
        let envelope_receipt_sha256 =
            string_field(&envelope, "/receipt_sha256", "envelope.receipt_sha256")?;
        if envelope_receipt_sha256 != actual_receipt_sha256 {
            return Err(vec![
                "envelope receipt_sha256 does not match the exact receipt bytes".to_owned(),
            ]);
        }

        let actual_corpus_sha256 = super::sha256_hex(corpus_source.as_bytes());
        let challenge_corpus_sha256 =
            string_field(&challenge, "/corpus_sha256", "challenge.corpus_sha256")?;
        let receipt_corpus_sha256 =
            string_field(&receipt, "/corpus_sha256", "receipt.corpus_sha256")?;
        if challenge_corpus_sha256 != actual_corpus_sha256
            || receipt_corpus_sha256 != actual_corpus_sha256
        {
            return Err(vec![
                "challenge and receipt must bind the exact corpus bytes".to_owned(),
            ]);
        }

        let challenge_policy_sha256 = string_field(
            &challenge,
            "/approved_policy_sha256",
            "challenge.approved_policy_sha256",
        )?;
        let receipt_policy_sha256 = string_field(
            &receipt,
            "/approved_policy_sha256",
            "receipt.approved_policy_sha256",
        )?;
        if challenge_policy_sha256 != receipt_policy_sha256 {
            return Err(vec![
                "receipt approved policy digest does not match the challenged policy".to_owned(),
            ]);
        }

        let challenge_target = string_field(&challenge, "/target_token", "challenge.target_token")?;
        let receipt_target = string_field(&receipt, "/target_token", "receipt.target_token")?;
        if challenge_target != receipt_target {
            return Err(vec![
                "receipt target token does not match the challenged target".to_owned(),
            ]);
        }

        let receipt_evidence_class =
            string_field(&receipt, "/evidence_class", "receipt.evidence_class")?;
        if !matches!(
            receipt_evidence_class,
            "namespace_lab_observation" | "lab_observation_claim"
        ) {
            return Err(vec![
                "freshness verification requires a non-synthetic lab observation".to_owned(),
            ]);
        }

        let started_at = integer_field(
            &envelope,
            "/started_at_unix_ms",
            "envelope.started_at_unix_ms",
        )?;
        let completed_at = integer_field(
            &envelope,
            "/completed_at_unix_ms",
            "envelope.completed_at_unix_ms",
        )?;
        if started_at < issued_at {
            return Err(vec![
                "receipt run started before this challenge was issued".to_owned(),
            ]);
        }
        if completed_at < started_at {
            return Err(vec![
                "receipt completion time precedes its start time".to_owned(),
            ]);
        }
        if completed_at > verifier_now_unix_ms || completed_at > expires_at {
            return Err(vec![
                "receipt completed after verifier time or challenge expiry".to_owned(),
            ]);
        }
        if verifier_now_unix_ms - completed_at > max_receipt_age {
            return Err(vec![
                "receipt is older than the challenge's maximum receipt age".to_owned(),
            ]);
        }

        let wall_anchor = receipt
            .pointer("/time_basis/wall_anchor_unix_ms")
            .and_then(Value::as_u64)
            .ok_or_else(|| vec!["receipt lacks an integer wall-clock anchor".to_owned()])?;
        let monotonic_origin = receipt
            .pointer("/time_basis/monotonic_origin_ms")
            .and_then(Value::as_u64)
            .ok_or_else(|| vec!["receipt lacks an integer monotonic origin".to_owned()])?;
        let observations = receipt
            .get("observations")
            .and_then(Value::as_array)
            .ok_or_else(|| vec!["receipt.observations must be an array".to_owned()])?;
        let mut prior_elapsed = None;
        for (index, observation) in observations.iter().enumerate() {
            let source = string_field(
                observation,
                "/evidence_source",
                &format!("receipt.observations[{index}].evidence_source"),
            )?;
            if source != "independent_dataplane_probe" {
                return Err(vec![format!(
                    "receipt.observations[{index}] is not an independent data-plane probe"
                )]);
            }

            let observed_at = integer_field(
                observation,
                "/observed_at_unix_ms",
                &format!("receipt.observations[{index}].observed_at_unix_ms"),
            )?;
            if observed_at < started_at || observed_at > completed_at {
                return Err(vec![format!(
                    "receipt.observations[{index}] timestamp is outside the envelope run interval"
                )]);
            }

            let elapsed = integer_field(
                observation,
                "/monotonic_elapsed_ms",
                &format!("receipt.observations[{index}].monotonic_elapsed_ms"),
            )?;
            if prior_elapsed.is_some_and(|previous| elapsed < previous) {
                return Err(vec![format!(
                    "receipt.observations[{index}] reverses monotonic trial order"
                )]);
            }
            let relative_elapsed = elapsed.checked_sub(monotonic_origin).ok_or_else(|| {
                vec![format!(
                    "receipt.observations[{index}] predates the monotonic origin"
                )]
            })?;
            let reconstructed_time =
                wall_anchor.checked_add(relative_elapsed).ok_or_else(|| {
                    vec![format!(
                        "receipt.observations[{index}] reconstructed wall time overflows"
                    )]
                })?;
            if reconstructed_time != observed_at {
                return Err(vec![format!(
                    "receipt.observations[{index}] wall and monotonic timestamps disagree"
                )]);
            }
            prior_elapsed = Some(elapsed);
        }

        // Challenge freshness is not enough: promotion also requires the normal
        // frozen-corpus reconciliation to be conformant for these exact bytes.
        let report = super::reconcile(
            corpus_schema_source,
            corpus_source,
            RECEIPT_SCHEMA,
            receipt_source,
        )?;
        if report["disposition"] != "reported_observations_consistent_not_authenticated" {
            return Err(vec![format!(
                "receipt did not qualify under normal conformance reconciliation: {}",
                report["disposition"]
            )]);
        }

        // Consume only after all schema, identity, age, evidence, and conformance checks pass.
        self.consumed_nonces.insert(nonce.to_owned());

        Ok(json!({
            "schema_version": "1.0.0",
            "challenge_id": challenge_id,
            "run_id": receipt_run_id,
            "policy_generation": generation,
            "receipt_sha256": actual_receipt_sha256,
            "corpus_sha256": actual_corpus_sha256,
            "approved_policy_sha256": receipt_policy_sha256,
            "receipt_age_ms": verifier_now_unix_ms - completed_at,
            "observations_checked": observations.len(),
            "disposition": "freshness_consistent_not_authenticated",
            "claim_ceiling": "challenge_and_byte_binding_consistent_not_signer_or_device_authenticated",
            "replay_guard": "nonce_consumed_in_memory_only",
            "conformance_disposition": report["disposition"]
        }))
    }
}

fn string_field<'a>(value: &'a Value, pointer: &str, label: &str) -> Result<&'a str, Vec<String>> {
    value
        .pointer(pointer)
        .and_then(Value::as_str)
        .ok_or_else(|| vec![format!("{label} must be a string")])
}

fn integer_field(value: &Value, pointer: &str, label: &str) -> Result<u64, Vec<String>> {
    value
        .pointer(pointer)
        .and_then(Value::as_u64)
        .ok_or_else(|| vec![format!("{label} must be an unsigned integer")])
}

#[cfg(test)]
mod tests {
    use super::ChallengeReplayGuard;
    use crate::sha256_hex;
    use serde_json::{Value, json};

    const CORPUS_SCHEMA: &str =
        include_str!("../../../schemas/edge-policy-conformance-corpus-v1.schema.json");
    const CORPUS: &str =
        include_str!("../../../examples/edge-policy-conformance-corpus-synthetic-v1.json");
    const CHALLENGE_ID: &str = "challenge-test-0001";
    const NONCE: &str = "cccccccccccccccccccccccccccccccccccccccccccccccccccccccccccccccc";
    const ISSUED_AT: u64 = 1_000;
    const STARTED_AT: u64 = 1_050;
    const COMPLETED_AT: u64 = 1_200;
    const EXPIRES_AT: u64 = 2_000;
    const POLICY_SHA256: &str = "aaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaa";
    const TARGET: &str = "target-synthetic-lab";

    fn receipt_source() -> String {
        let mut receipt = crate::build_synthetic_receipt(CORPUS).expect("synthetic template");
        receipt["evidence_class"] = json!("namespace_lab_observation");
        receipt["run_id"] = json!("run-freshness-0001");
        receipt["approved_policy_sha256"] = json!(POLICY_SHA256);
        receipt["effective_config_sha256"] = json!("b".repeat(64));
        receipt["target_token"] = json!(TARGET);
        receipt["time_basis"] = json!({
            "kind": "monotonic_with_wall_anchor",
            "clock_id": "freshness-test-clock",
            "wall_anchor_unix_ms": STARTED_AT,
            "monotonic_origin_ms": 0
        });
        for (index, observation) in receipt["observations"]
            .as_array_mut()
            .expect("observations array")
            .iter_mut()
            .enumerate()
        {
            observation["evidence_source"] = json!("independent_dataplane_probe");
            observation["observed_at_unix_ms"] = json!(STARTED_AT + index as u64);
            observation["monotonic_elapsed_ms"] = json!(index as u64);
            observation["duration_ms"] = json!(5);
            observation["evidence_sha256"] = json!("d".repeat(64));
            observation["effective_policy_sha256"] = json!("b".repeat(64));
        }
        serde_json::to_string(&receipt).expect("serialize receipt")
    }

    fn challenge_source() -> String {
        json!({
            "schema_version": "1.0.0",
            "challenge_id": CHALLENGE_ID,
            "nonce": NONCE,
            "issued_at_unix_ms": ISSUED_AT,
            "expires_at_unix_ms": EXPIRES_AT,
            "max_receipt_age_ms": 500,
            "policy_generation": 7,
            "corpus_sha256": sha256_hex(CORPUS.as_bytes()),
            "approved_policy_sha256": POLICY_SHA256,
            "target_token": TARGET
        })
        .to_string()
    }

    fn envelope_source(receipt: &str) -> String {
        let receipt_value: Value = serde_json::from_str(receipt).expect("receipt JSON");
        let run_id = receipt_value["run_id"].as_str().expect("receipt run_id");
        json!({
            "schema_version": "1.0.0",
            "challenge_id": CHALLENGE_ID,
            "nonce": NONCE,
            "run_id": run_id,
            "policy_generation": 7,
            "started_at_unix_ms": STARTED_AT,
            "completed_at_unix_ms": COMPLETED_AT,
            "receipt_sha256": sha256_hex(receipt.as_bytes())
        })
        .to_string()
    }

    fn verify(
        guard: &mut ChallengeReplayGuard,
        challenge: &str,
        envelope: &str,
        receipt: &str,
        now: u64,
    ) -> Result<Value, Vec<String>> {
        guard.verify_and_consume(challenge, envelope, CORPUS_SCHEMA, CORPUS, receipt, now)
    }

    #[test]
    fn fresh_challenge_and_conformant_receipt_are_accepted_once() {
        let receipt = receipt_source();
        let challenge = challenge_source();
        let envelope = envelope_source(&receipt);
        let mut guard = ChallengeReplayGuard::new();

        let report =
            verify(&mut guard, &challenge, &envelope, &receipt, 1_400).expect("fresh receipt");
        assert_eq!(
            report["disposition"],
            "freshness_consistent_not_authenticated"
        );
        assert_eq!(
            report["conformance_disposition"],
            "reported_observations_consistent_not_authenticated"
        );
        assert_eq!(report["receipt_age_ms"], 200);
        assert_eq!(report["observations_checked"], 13);
    }

    #[test]
    fn replay_of_consumed_nonce_is_rejected() {
        let receipt = receipt_source();
        let challenge = challenge_source();
        let envelope = envelope_source(&receipt);
        let mut guard = ChallengeReplayGuard::new();
        verify(&mut guard, &challenge, &envelope, &receipt, 1_400).expect("first receipt");
        let error = verify(&mut guard, &challenge, &envelope, &receipt, 1_400)
            .expect_err("replay rejected");
        assert!(
            error
                .iter()
                .any(|item| item.contains("already been consumed"))
        );
    }

    #[test]
    fn stale_receipt_is_rejected_without_consuming_nonce() {
        let receipt = receipt_source();
        let challenge = challenge_source();
        let envelope = envelope_source(&receipt);
        let mut guard = ChallengeReplayGuard::new();
        let error = verify(&mut guard, &challenge, &envelope, &receipt, 1_901)
            .expect_err("age exceeds declared maximum");
        assert!(
            error
                .iter()
                .any(|item| item.contains("maximum receipt age"))
        );
        let valid = verify(&mut guard, &challenge, &envelope, &receipt, 1_400);
        assert!(valid.is_ok(), "invalid attempt must not consume the nonce");
    }

    #[test]
    fn mismatched_nonce_and_policy_generation_are_rejected() {
        let receipt = receipt_source();
        let mut guard = ChallengeReplayGuard::new();
        let mut wrong_nonce: Value = serde_json::from_str(&challenge_source()).expect("challenge");
        wrong_nonce["nonce"] = json!("e".repeat(64));
        let error = verify(
            &mut guard,
            &wrong_nonce.to_string(),
            &envelope_source(&receipt),
            &receipt,
            1_400,
        )
        .expect_err("nonce mismatch");
        assert!(
            error
                .iter()
                .any(|item| item.contains("challenge ID and nonce"))
        );

        let mut wrong_generation: Value =
            serde_json::from_str(&envelope_source(&receipt)).expect("envelope");
        wrong_generation["policy_generation"] = json!(8);
        let error = verify(
            &mut guard,
            &challenge_source(),
            &wrong_generation.to_string(),
            &receipt,
            1_400,
        )
        .expect_err("generation mismatch");
        assert!(error.iter().any(|item| item.contains("policy_generation")));
    }

    #[test]
    fn exact_receipt_bytes_are_bound_and_synthetic_receipts_are_rejected() {
        let receipt = receipt_source();
        let mut guard = ChallengeReplayGuard::new();
        let pretty = serde_json::to_string_pretty(
            &serde_json::from_str::<Value>(&receipt).expect("receipt JSON"),
        )
        .expect("pretty receipt");
        let error = verify(
            &mut guard,
            &challenge_source(),
            &envelope_source(&receipt),
            &pretty,
            1_400,
        )
        .expect_err("changed bytes");
        assert!(
            error
                .iter()
                .any(|item| item.contains("exact receipt bytes"))
        );

        let synthetic = crate::build_synthetic_receipt(CORPUS).expect("synthetic receipt");
        let synthetic_source = serde_json::to_string(&synthetic).expect("serialize");
        let error = verify(
            &mut guard,
            &challenge_source(),
            &envelope_source(&synthetic_source),
            &synthetic_source,
            1_400,
        )
        .expect_err("synthetic evidence isn't fresh dataplane evidence");
        assert!(
            error
                .iter()
                .any(|item| item.contains("non-synthetic lab observation"))
        );
    }

    #[test]
    fn target_policy_and_corpus_bindings_are_enforced() {
        let receipt = receipt_source();
        let envelope = envelope_source(&receipt);
        let mut guard = ChallengeReplayGuard::new();

        let mut wrong_target: Value = serde_json::from_str(&challenge_source()).expect("challenge");
        wrong_target["target_token"] = json!("target-other-lab");
        let error = verify(
            &mut guard,
            &wrong_target.to_string(),
            &envelope,
            &receipt,
            1_400,
        )
        .expect_err("target mismatch");
        assert!(error.iter().any(|item| item.contains("target token")));

        let mut wrong_policy: Value = serde_json::from_str(&challenge_source()).expect("challenge");
        wrong_policy["approved_policy_sha256"] = json!("f".repeat(64));
        let error = verify(
            &mut guard,
            &wrong_policy.to_string(),
            &envelope,
            &receipt,
            1_400,
        )
        .expect_err("policy mismatch");
        assert!(
            error
                .iter()
                .any(|item| item.contains("approved policy digest"))
        );

        let mut wrong_corpus: Value = serde_json::from_str(&challenge_source()).expect("challenge");
        wrong_corpus["corpus_sha256"] = json!("f".repeat(64));
        let error = verify(
            &mut guard,
            &wrong_corpus.to_string(),
            &envelope,
            &receipt,
            1_400,
        )
        .expect_err("corpus mismatch");
        assert!(error.iter().any(|item| item.contains("exact corpus bytes")));
    }

    #[test]
    fn wall_and_monotonic_timestamp_fields_must_agree() {
        let receipt = receipt_source();
        let mut tampered: Value = serde_json::from_str(&receipt).expect("receipt");
        tampered["observations"][0]["observed_at_unix_ms"] = json!(STARTED_AT + 3);
        let tampered_source = tampered.to_string();
        let mut guard = ChallengeReplayGuard::new();
        let error = verify(
            &mut guard,
            &challenge_source(),
            &envelope_source(&tampered_source),
            &tampered_source,
            1_400,
        )
        .expect_err("wall and monotonic time disagree");
        assert!(
            error
                .iter()
                .any(|item| item.contains("timestamps disagree"))
        );
    }

    #[test]
    fn challenge_expiry_and_observation_time_bounds_are_enforced() {
        let receipt = receipt_source();
        let challenge = challenge_source();
        let envelope = envelope_source(&receipt);
        let mut guard = ChallengeReplayGuard::new();
        let error = verify(&mut guard, &challenge, &envelope, &receipt, EXPIRES_AT + 1)
            .expect_err("expired challenge");
        assert!(error.iter().any(|item| item.contains("not current")));

        let mut tampered: Value = serde_json::from_str(&receipt).expect("receipt");
        tampered["observations"][0]["observed_at_unix_ms"] = json!(STARTED_AT - 1);
        let tampered_source = tampered.to_string();
        let error = verify(
            &mut guard,
            &challenge,
            &envelope_source(&tampered_source),
            &tampered_source,
            1_400,
        )
        .expect_err("observation predates run");
        assert!(
            error
                .iter()
                .any(|item| item.contains("outside the envelope run interval"))
        );
    }
}
